/**
 * "каждую среду", "каждый понедельник", "каждое воскресенье": the weekday
 * arrives in the nominative, and «каждый» takes the accusative and its gender.
 */
function everyRu(day: string): string {
  const word = day.trim().toLowerCase();
  if (!/[а-яё]/.test(word)) return `каждый ${day}`;
  if (word.endsWith("а")) return `каждую ${word.slice(0, -1)}у`;
  if (word.endsWith("е")) return `каждое ${word}`;
  return `каждый ${word}`;
}

